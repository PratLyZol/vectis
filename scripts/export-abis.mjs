// Exports the interface ABIs from the Foundry build to TypeScript for web and keeper.
// Usage: node scripts/export-abis.mjs   (run `forge build` in /contracts first)
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const names = ["IPriceOracle", "ILendingVault", "IMarginManager"];
const exportName = { IPriceOracle: "priceOracleAbi", ILendingVault: "lendingVaultAbi", IMarginManager: "marginManagerAbi" };

let out = "// AUTO-GENERATED by scripts/export-abis.mjs from contracts/src/interfaces. Do not edit.\n";
out += "// ERC-20 and ERC-4626 ABIs come from viem (erc20Abi, erc4626Abi).\n\n";
for (const n of names) {
  const artifact = JSON.parse(readFileSync(join(root, "contracts", "out", `${n}.sol`, `${n}.json`), "utf8"));
  out += `export const ${exportName[n]} = ${JSON.stringify(artifact.abi, null, 2)} as const;\n\n`;
}

for (const target of [join(root, "web", "src", "config", "abis.ts"), join(root, "keeper", "src", "abis.ts")]) {
  mkdirSync(dirname(target), { recursive: true });
  writeFileSync(target, out);
  console.log("wrote", target);
}
